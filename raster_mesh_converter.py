    def get_data(self):
        import os
        import csv

        type_of_code = self.dlg.radioButton.isChecked()
        prefix = "20"
        if type_of_code:
            dict_meshsize_no = {0: 80000, 1: 10000, 2: 5000, 3: 2000, 4: 1000, 5: 500, 6: 250, 7: 200, 8: 125,
                                9: 100, 10: 50, 11: 20, 12: 10, 13: 5, 14: 2, 15: 1}
        else:
            dict_meshsize_no = {0: 80000, 1: 10000, 2: 5000, 3: 2000, 4: 1000, 5: 500, 6: 250, 7: 125}
            prefix = ""

        # 現在のキャンバスの表示範囲（地図座標系）
        extent = self.iface.mapCanvas().extent()

        # 現在のプロジェクトの CRS（例: EPSG:qgis ラスタレイヤ 画面表示されている四隅の緯度経度をpythonで求める方法3857 など）
        src_crs = self.iface.mapCanvas().mapSettings().destinationCrs()

        # 緯度経度（EPSG:4326）に変換するための CRS
        dest_crs = QgsCoordinateReferenceSystem("EPSG:4326")
        # dest_crs = QgsCoordinateReferenceSystem("EPSG:3857")

        # 座標変換オブジェクトを作成
        transform = QgsCoordinateTransform(src_crs, dest_crs, QgsProject.instance())

        # 四隅の座標を変換
        top_left = transform.transform(extent.xMinimum(), extent.yMaximum())
        top_right = transform.transform(extent.xMaximum(), extent.yMaximum())
        bottom_left = transform.transform(extent.xMinimum(), extent.yMinimum())
        bottom_right = transform.transform(extent.xMaximum(), extent.yMinimum())

        top_left = (top_left.y(), top_left.x())
        top_right = (top_right.y(), top_right.x())
        bottom_left = (bottom_left.y(), bottom_left.x())
        bottom_right = (bottom_right.y(), bottom_right.x())

        mesh_size_no = self.dlg.comboBox.currentIndex()
        mesh_size_coefficient = dict_meshsize_no[mesh_size_no]

        # 東西南北のxy座標
        coordinate_bottom_left = LatitudeAndLongitude(latitude=bottom_left[0], longitude=bottom_left[1]).get_coordinate(mesh_size_coefficient)
        coordinate_top_right = LatitudeAndLongitude(latitude=top_right[0], longitude=top_right[1]).get_coordinate(mesh_size_coefficient)

        # メッシュ数
        mesh_number = (coordinate_top_right["x"] - coordinate_bottom_left["x"] + 1) \
                    * (coordinate_top_right["y"] - coordinate_bottom_left["y"] + 1)

        # メッシュ数がlimit_numberを超えない設定
        limit_number = 1000000
        if mesh_number > limit_number:
            QMessageBox.information(None, "警告", f"メッシュが{limit_number}を超えています。\n再設定してください。", QMessageBox.Yes)
        else:
            # 範囲内の全座標
            dict_coordinates = [{"x": x, "y": y} for x in
                                range(coordinate_bottom_left["x"], coordinate_top_right["x"] + 1)
                                for y in range(coordinate_bottom_left["y"], coordinate_top_right["y"] + 1)]

            # data list
            list_data = []

            for coordinate in dict_coordinates:
                latitude_North = (coordinate["y"] + 1) * 2 / 3 / (80000 / mesh_size_coefficient)
                latitude_South = coordinate["y"] * 2 / 3 / (80000 / mesh_size_coefficient)
                longitude_East = (coordinate["x"] + 1) / (80000 / mesh_size_coefficient) + 100
                longitude_West = coordinate["x"] / (80000 / mesh_size_coefficient) + 100
                mesh_code = prefix + str(Coordinate(x=coordinate["x"], y=coordinate["y"]).get_mesh_code(mesh_size_coefficient))
                center_longitude = (longitude_East + longitude_West) / 2
                center_latitude = (latitude_North + latitude_South) / 2
                # 例: ラスタファイルを読み込み
                rlayer = self.iface.activeLayer()
                if not rlayer.isValid():
                    raise ValueError("Raster layer is invalid")
                # バンド番号（1バンド目）
                band = 1

                try:
                    value = rlayer.dataProvider().sample(QgsPointXY(center_longitude, center_latitude), band)
                    data = {"coordinate": str(coordinate["x"]) + "," + str(coordinate["y"]),
                            "WKT": LatitudeAndLongitude.dict2wkt(North=latitude_North,
                                                                 South=latitude_South,
                                                                 East=longitude_East,
                                                                 West=longitude_West),
                            "meshcode": mesh_code,
                            "value": value[0]
                            }
                    if value[1]:
                        list_data.append(data)
                except AttributeError:
                    QMessageBox.information(None, "警告", "対象のレイヤを選びなおしてください。", QMessageBox.Yes)
                    break

            layer = QgsVectorLayer('Polygon', rlayer.name(), 'memory')
            pr = layer.dataProvider()

            # new fieldの追加
            new_fields = [QgsField("メッシュコード", QVariant.String),
                          QgsField("value", QVariant.String),
                          ]
            pr.addAttributes(new_fields)
            layer.updateFields()

            for row in list_data:
                # polygon追加
                poly = QgsFeature()
                geom = QgsGeometry.fromWkt(row["WKT"])
                poly.setGeometry(geom)

                # new fieldに
                poly.setAttributes([row["meshcode"],
                                    row["value"],
                                    ])

                # new featureを追加
                pr.addFeatures([poly])

            if list_data:
                layer.updateExtents()

                # 現在のシンボルを取得
                symbol = layer.renderer().symbol()

                # 塗りつぶし色を取得
                current_color = symbol.color()

                # 新しい色（透明度を下げる）
                # QColor(R, G, B, Alpha)  Alpha=0〜255
                new_color = QColor(current_color.red(),
                                   current_color.green(),
                                   current_color.blue(),
                                   100)  # 100 は半透明

                # 色を設定
                symbol.setColor(new_color)

                # レイヤーを再描画
                layer.triggerRepaint()

                QgsProject.instance().addMapLayers([layer])

                # ポリゴンの色分け
                field_name = "value"
                unique_values = layer.uniqueValues(layer.fields().indexFromName(field_name))
                source_symbol = QgsSymbol.defaultSymbol(layer.geometryType())
                categories = []
                for val in unique_values:
                    symbol = source_symbol.clone()
                    color = QgsSymbol.defaultSymbol(layer.geometryType()).color()
                    symbol.setColor(QColor(random.randint(0, 255), random.randint(0, 255), random.randint(0, 255)))

                    category = QgsRendererCategory(val, symbol, str(val))
                    categories.append(category)

                renderer =QgsCategorizedSymbolRenderer(field_name, categories)
                layer.setRenderer(renderer)

                layer.triggerRepaint()
                iface.layerTreeView().refreshLayerSymbology(layer.id())


